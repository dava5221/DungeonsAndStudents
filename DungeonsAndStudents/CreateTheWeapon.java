package DungeonsAndStudents;

public class CreateTheWeapon extends Weapon{
    public CreateTheWeapon(String rare,double endurance,double speedOfAttack,double magicDamage,double physicDamage,String typeOfWeapon){
        this.rare = rare;
        this.endurance = endurance;
        this.speedOfAttack = speedOfAttack;
        this.magicDamage = magicDamage;
        this.physicDamage = physicDamage;
        this.typeOfWeapon = typeOfWeapon;
    }
}
