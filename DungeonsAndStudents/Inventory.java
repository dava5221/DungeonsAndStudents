package DungeonsAndStudents;

public class Inventory {
    private Armor helmet;
    private Armor chest;
    private Armor pants;
    private Armor boots;
    private Weapon weapon;

    public Armor getHelmet() {return helmet;}
    public void setHelmet(Armor helmet){this.helmet = helmet;}
    public Armor getChest() {return chest;}
    public void setChest(Armor chest){this.chest = chest;}
    public Armor getPants(){return pants;}
    public void setPants(Armor pants){this.pants = pants;}
    public Armor getBoots(){return boots;}
    public void setBoots(Armor boots){this.boots = boots;}
    public Weapon getWeapon(){return weapon;}
    public void setWeapon(Weapon weapon){this.weapon = weapon;}


}
